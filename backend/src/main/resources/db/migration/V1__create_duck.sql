CREATE TABLE duck (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color     VARCHAR(16)   NOT NULL,
    duck_size VARCHAR(16)   NOT NULL,
    price     DECIMAL(10,2) NOT NULL,
    quantity  INT           NOT NULL,
    deleted   BOOLEAN       NOT NULL DEFAULT FALSE,
    -- The warehouse merge rule as a database invariant: one row per color/size/price.
    CONSTRAINT uq_duck_color_size_price UNIQUE (color, duck_size, price)
);
